/** WidgetTokens.swift for the ChronirWidgets target (which cannot see ColorTokens.swift). */
function iosWidgetTokens({ dictionary }) {
  const colors = tree(dictionary.allTokens, ['color', 'ios']);
  const find = (section, name) => {
    const node = colors.get(section)?.get(name);
    if (!node) throw new Error(`WidgetTokens: missing color.ios.${section}.${name}`);
    return node;
  };
  const member = (widgetName, section, name, attrs = []) => {
    const node = find(section, name);
    if (isAdaptive(node)) {
      const v = (mode) => swiftHex(node.get(mode).value);
      return [...attrs, `    static let ${widgetName} = adaptive(light: ${v('light')}, dark: ${v('dark')})`];
    }
    return [...attrs, `    static let ${widgetName} = Color(hex: ${swiftHex(node.value)})`];
  };
  const deprecated = (replacement) => [`    @available(*, deprecated, message: "Use ${replacement} (adapts to light/dark)")`];
  const staticOf = (section, name, mode) => {
    const node = find(section, name);
    return `Color(hex: ${swiftHex(isAdaptive(node) ? node.get(mode).value : node.value)})`;
  };
  const categories = ['Home', 'Health', 'Finance', 'Vehicle', 'Work', 'Personal', 'Pets', 'Subscriptions'];
  const spacing = Object.fromEntries(
    dictionary.allTokens.filter((t) => t.path[0] === 'spacing' && t.path.length === 2).map((t) => [t.path[1], numberLiteral(t.value)]),
  );
  return [
    ...fileHeader('//'),
    'import SwiftUI',
    '#if canImport(UIKit)',
    'import UIKit',
    '#endif',
    '',
    '/// Design token subset for the widget extension, generated from the same JSON as ColorTokens.swift.',
    '/// Colors are adaptive (light/dark) via UIColor providers, which WidgetKit resolves per rendering context.',
    'enum WidgetTokens {',
    '    // MARK: - Colors',
    '',
    ...member('primary', 'adaptive', 'primary'),
    ...member('onPrimary', 'adaptive', 'onPrimary'),
    ...member('textPrimary', 'adaptive', 'textPrimary'),
    ...member('textSecondary', 'adaptive', 'textSecondary'),
    ...member('textTertiary', 'adaptive', 'textTertiary'),
    ...member('textWarning', 'adaptive', 'textWarning'),
    ...member('backgroundPrimary', 'adaptive', 'backgroundPrimary'),
    ...member('surfaceCard', 'adaptive', 'surfaceCard'),
    ...member('accent', 'semantic', 'warning', ['    /// Amber fill/icon accent — not text-safe on light; use textWarning for text']),
    '',
    ...deprecated('primary'),
    `    static let primaryDark = ${staticOf('adaptive', 'primary', 'dark')}`,
    ...deprecated('backgroundPrimary'),
    `    static let backgroundDark = ${staticOf('adaptive', 'backgroundPrimary', 'dark')}`,
    ...deprecated('surfaceCard'),
    `    static let surfaceCardDark = ${staticOf('adaptive', 'surfaceCard', 'dark')}`,
    '',
    '    // MARK: - Category Colors',
    '',
    '    /// Vivid category fill / icon color.',
    '    static func categoryColor(for name: String?) -> Color {',
    '        switch name {',
    ...categories.map((c) => `        case "${camel(c)}": return ${staticOf('category', `category${c}`, 'light')}`),
    `        default: return ${staticOf('category', 'categoryHome', 'light')}`,
    '        }',
    '    }',
    '',
    '    /// Fill for text-bearing category badges (pairs with `categoryBadgeForeground(for:)`, >= 4.5:1).',
    '    static func categoryBadgeBackground(for name: String?) -> Color {',
    '        switch name {',
    ...categories.map((c) => `        case "${camel(c)}": return ${staticOf('badgePairs', `badge${c}Background`, 'light')}`),
    `        default: return ${staticOf('badgePairs', 'badgeHomeBackground', 'light')}`,
    '        }',
    '    }',
    '',
    '    /// Text/icon color on `categoryBadgeBackground(for:)`.',
    '    static func categoryBadgeForeground(for name: String?) -> Color {',
    '        switch name {',
    ...categories.map((c) => `        case "${camel(c)}": return ${staticOf('badgePairs', `badge${c}Foreground`, 'light')}`),
    `        default: return ${staticOf('badgePairs', 'badgeHomeForeground', 'light')}`,
    '        }',
    '    }',
    '',
    '    // MARK: - Spacing',
    '',
    `    static let spacingXS: CGFloat = ${spacing.xxs}`,
    `    static let spacingSM: CGFloat = ${spacing.xs}`,
    `    static let spacingMD: CGFloat = ${spacing.sm}`,
    `    static let spacingLG: CGFloat = ${spacing.md}`,
    `    static let touchMinTarget: CGFloat = ${spacing.touchMinTarget}`,
    '',
    '    // MARK: - Adaptive Helper',
    '',
    '    private static func adaptive(light: UInt, dark: UInt) -> Color {',
    '        #if canImport(UIKit)',
    '        return Color(UIColor { traits in',
    '            let hex = traits.userInterfaceStyle == .dark ? dark : light',
    '            return UIColor(',
    '                red: CGFloat((hex >> 16) & 0xFF) / 255,',
    '                green: CGFloat((hex >> 8) & 0xFF) / 255,',
    '                blue: CGFloat(hex & 0xFF) / 255,',
    '                alpha: 1',
    '            )',
    '        })',
    '        #else',
    '        return Color(hex: dark)',
    '        #endif',
    '    }',
    '}',
    '',
    '// Color hex initializer (the widget extension does not compile ColorTokens.swift)',
    'extension Color {',
    '    init(hex: UInt, opacity: Double = 1.0) {',
    '        let red = Double((hex >> 16) & 0xFF) / 255.0',
    '        let green = Double((hex >> 8) & 0xFF) / 255.0',
    '        let blue = Double(hex & 0xFF) / 255.0',
    '        self.init(.sRGB, red: red, green: green, blue: blue, opacity: opacity)',
    '    }',
    '}',
    '',
  ].join('\n');
}

