// ---------------------------------------------------------------- typography

function typographyRoles(dictionary, platform) {
  const scale = tree(dictionary.allTokens, ['typography', 'scale']);
  const alias = tree(dictionary.allTokens, ['typography', 'alias']);
  const min = dictionary.allTokens.find((t) => t.path.join('.') === 'typography.minimumSize');
  const roles = [...scale].map(([name, props]) => {
    const p = (key) => (props.has(key) ? valueFor(props.get(key), platform) : undefined);
    return {
      name,
      comment: props.get('fontSize').comment,
      size: numberLiteral(p('fontSize')),
      lineHeight: numberLiteral(p('lineHeight')),
      weight: p('fontWeight'),
      letterSpacing: parseFloat(p('letterSpacing') ?? '0'),
      design: p('design') ?? 'default',
      textStyle: p('textStyle'),
      maxScale: p('maxDynamicTypeScale'),
    };
  });
  const aliases = [...alias].map(([name, token]) => ({ name, target: valueFor(token, platform) }));
  return { roles, aliases, minimum: numberLiteral(min.value) };
}

const SWIFT_WEIGHT = { regular: '.regular', medium: '.medium', semibold: '.semibold', bold: '.bold' };
const KOTLIN_WEIGHT = { regular: 'FontWeight.Normal', medium: 'FontWeight.Medium', semibold: 'FontWeight.SemiBold', bold: 'FontWeight.Bold' };
const M3_ROLES = [
  'displayLarge', 'displayMedium', 'displaySmall', 'headlineLarge', 'headlineMedium', 'headlineSmall',
  'titleLarge', 'titleMedium', 'titleSmall', 'bodyLarge', 'bodyMedium', 'bodySmall', 'labelLarge', 'labelMedium', 'labelSmall',
];

function iosTypography({ dictionary }) {
  const { roles, aliases, minimum } = typographyRoles(dictionary, 'ios');
  const spec = (r) => {
    const weight = SWIFT_WEIGHT[r.weight];
    if (!weight) throw new Error(`Unknown font weight ${r.weight}`);
    const args = [`size: ${r.size}`, `weight: ${weight}`];
    if (r.design !== 'default') args.push(`design: .${r.design}`);
    args.push(`textStyle: .${r.textStyle}`);
    if (r.maxScale !== undefined) args.push(`maxDynamicTypeScale: ${r.maxScale}`);
    const line = `    static let ${r.name}Spec = Spec(${args.join(', ')})`;
    if (line.length <= 120) return line;
    return [`    static let ${r.name}Spec = Spec(`, args.map((a) => `        ${a}`).join(',\n'), '    )'].join('\n');
  };
  return [
    ...fileHeader('//'),
    'import SwiftUI',
    '',
    'enum TypographyTokens {',
    '    /// One type role: base size at the default Dynamic Type setting plus the text style it scales with.',
    '    struct Spec {',
    '        let size: CGFloat',
    '        let weight: Font.Weight',
    '        var design: Font.Design = .default',
    '        let textStyle: Font.TextStyle',
    '        /// Upper bound on Dynamic Type growth (nil = unbounded). Display sizes are already large.',
    '        var maxDynamicTypeScale: CGFloat?',
    '',
    '        /// Final point size: Dynamic Type size (from `@ScaledMetric(relativeTo: textStyle)`), clamped by',
    '        /// `maxDynamicTypeScale`, multiplied by the in-app text-size preference, floored at `minimumSize`.',
    '        func resolvedSize(dynamicSize: CGFloat, appScale: CGFloat) -> CGFloat {',
    '            let capped = maxDynamicTypeScale.map { min(dynamicSize, size * $0) } ?? dynamicSize',
    '            return max(TypographyTokens.minimumSize, (capped * appScale).rounded())',
    '        }',
    '',
    '        func font(size: CGFloat) -> Font {',
    '            Font.system(size: size, weight: weight, design: design)',
    '        }',
    '',
    '        /// Fixed-size font (no Dynamic Type). Prefer `ChronirText` / `.chronirFont(_:)`.',
    '        var font: Font { font(size: size) }',
    '    }',
    '',
    `    static let minimumSize: CGFloat = ${minimum}`,
    '',
    '    // MARK: - Specs',
    '',
    ...roles.map(spec),
    '',
    '    // MARK: - Fixed-size fonts (do not scale; use ChronirText / .chronirFont for Dynamic Type)',
    '',
    ...roles.map((r) => `    static let ${r.name} = ${r.name}Spec.font`),
    '',
    '    // MARK: - Spec-Aligned Aliases (design-system.md Section 3.3)',
    '',
    ...aliases.flatMap((a) => [`    static let ${a.name}Spec = ${a.target}Spec`, `    static let ${a.name} = ${a.target}`]),
    '',
    '    // MARK: - Scaling',
    '',
    '    static func scaled(size: CGFloat, weight: Font.Weight, design: Font.Design = .default, scale: CGFloat) -> Font {',
    '        Font.system(size: max(minimumSize, (size * scale).rounded()), weight: weight, design: design)',
    '    }',
    '}',
    '',
  ].join('\n');
}

function androidTypography({ dictionary }) {
  const { roles, aliases, minimum } = typographyRoles(dictionary, 'android');
  const style = (r) => {
    const weight = KOTLIN_WEIGHT[r.weight];
    if (!weight) throw new Error(`Unknown font weight ${r.weight}`);
    const lines = ['        fontFamily = FontFamily.Default', `        fontWeight = ${weight}`, `        fontSize = ${r.size}.sp`, `        lineHeight = ${r.lineHeight}.sp`];
    if (r.letterSpacing !== 0) lines.push(`        letterSpacing = ${r.letterSpacing < 0 ? `(${r.letterSpacing})` : r.letterSpacing}.sp`);
    return [...kotlinDoc(r), `    val ${pascal(r.name)} = TextStyle(`, lines.join(',\n'), '    )', ''];
  };
  const names = new Set(roles.map((r) => r.name));
  const missing = M3_ROLES.filter((role) => !names.has(role));
  if (missing.length) throw new Error(`typography.json is missing M3 roles: ${missing.join(', ')}`);
  return [
    ...fileHeader('//'),
    `package ${KT_PACKAGE}`,
    '',
    'import androidx.compose.material3.Typography',
    'import androidx.compose.ui.text.TextStyle',
    'import androidx.compose.ui.text.font.FontFamily',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.unit.sp',
    '',
    'object TypographyTokens {',
    `    /** Floor (sp) applied after the in-app text-size multiplier. */`,
    `    const val MinimumFontSize = ${minimum}f`,
    '',
    ...roles.flatMap(style),
    '    // MARK: - Spec-Aligned Aliases (design-system.md Section 3.3)',
    '',
    ...aliases.map((a) => `    val ${pascal(a.name)} = ${pascal(a.target)}`),
    '',
    '    // MARK: - Material 3 Typography (one token per M3 role)',
    '',
    '    val AppTypography = Typography(',
    M3_ROLES.map((role) => `        ${role} = ${pascal(role)}`).join(',\n'),
    '    )',
    '',
    '    fun scaledTypography(scale: Float): Typography {',
    '        fun TextStyle.scaled() = copy(',
    '            fontSize = (fontSize.value * scale).coerceAtLeast(MinimumFontSize).sp,',
    '            lineHeight = lineHeight * scale',
    '        )',
    '        return Typography(',
    M3_ROLES.map((role) => `            ${role} = ${pascal(role)}.scaled()`).join(',\n'),
    '        )',
    '    }',
    '}',
    '',
  ].join('\n');
}

export function registerChronirFormats(StyleDictionary) {
  const formats = {
    'chronir/ios/colors': iosColors,
    'chronir/ios/typography': iosTypography,
    'chronir/ios/spacing': iosDimensions('spacing', 'SpacingTokens'),
    'chronir/ios/radius': iosDimensions('radius', 'RadiusTokens'),
    'chronir/ios/animation': iosAnimation,
    'chronir/ios/widgets': iosWidgetTokens,
    'chronir/android/colors': androidColors,
    'chronir/android/colorSchemes': androidColorSchemes,
    'chronir/android/extendedColors': androidExtendedColors,
    'chronir/android/typography': androidTypography,
    'chronir/android/spacing': androidDimensions('spacing', 'SpacingTokens'),
    'chronir/android/radius': androidDimensions('radius', 'RadiusTokens'),
    'chronir/android/animation': androidAnimation,
  };
  for (const [name, format] of Object.entries(formats)) {
    const wrapped = name.startsWith('chronir/android/') ? (args) => ktlintSpacing(format(args)) : format;
    StyleDictionary.registerFormat({ name, format: wrapped });
  }
}
