/**
 * Chronir Style Dictionary formats.
 *
 * These formats emit the exact token files the apps compile:
 *   iOS:     ColorTokens.swift, TypographyTokens.swift, SpacingTokens.swift, RadiusTokens.swift, AnimationTokens.swift
 *   Widgets: WidgetTokens.swift (build/ios-widgets/ -> chronir/ChronirWidgets/Shared/)
 *   Android: ColorTokens.kt, ColorSchemeTokens.kt, ExtendedColorTokens.kt, TypographyTokens.kt,
 *            SpacingTokens.kt, RadiusTokens.kt, AnimationTokens.kt
 *
 * Token conventions (see tokens/*.json):
 *   - color.ios.<section>.<member> / color.android.<section>.<Member>
 *       leaf                      -> static color
 *       {light, dark[, lightHighContrast, darkHighContrast]} -> adaptive color
 *   - color.android.scheme.<m3Role>.{light,dark} -> full Material 3 ColorScheme
 *   - `platforms: ["android"]` restricts a token to one platform
 *   - `androidValue` overrides `value` on Android; `androidName` names the Kotlin member
 *   - `aliasOf: "<key>"` emits an alias to another member of the same file
 */

